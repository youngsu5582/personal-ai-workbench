-- 모델의 단가표. 한 벌이 provider · model · 적용 기간으로 정해진다. 근거는 docs/adr/0002-price-book-in-db.md 에 있다.
--
-- 관리 API 없이 마이그레이션으로만 넣고 바꾼다. 누가 어떤 근거로 바꿨는지가 PR 에 남는다.
-- 적용된 표의 단가는 고치지 않는다. 단가가 바뀌면 이 표의 effective_to 를 닫고 새 표를 더한다.
CREATE TABLE model_price_books (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider       varchar(255)                NOT NULL,
    model          varchar(255)                NOT NULL,

    -- [from, to) 다. called_at 이 effective_to 와 같으면 다음 표가 받는다 — 경계 시각에 두 단가가 겹치지 않는다.
    effective_from timestamp(6) with time zone NOT NULL,
    -- NULL 이면 지금 적용 중이다.
    effective_to   timestamp(6) with time zone,

    -- 단가의 출처.
    source_url     varchar(1024)               NOT NULL,

    -- usage_raw 안의 경로 → 1M 당 USD. 모양은 PriceRates 가 정한다.
    --   {"usdPerMillion": {"input_tokens_details.text_tokens": 5, "output_tokens": 30}}
    -- 점이 중첩을 가른다. Provider 의 필드명이 여기 데이터로 있어서, 계산하는 코드는 Provider 를 모른다.
    --
    -- 행으로 펼치지 않는다. 표 한 장이 늘 통째로 읽히고 그 안을 SQL 로 묻지 않으며, 경로의 종류가 모델마다 다르다.
    -- 값에는 DB 제약을 걸지 않는다. 빈 표 · 음수 단가는 PriceRates 의 생성자가 막고, DB 에서 읽을 때도 그 생성자를 거친다.
    rates          jsonb                       NOT NULL,

    CONSTRAINT ck_model_price_books_period CHECK (effective_to IS NULL OR effective_from < effective_to)
);

-- 같은 모델의 기간 겹침은 DB 로 막지 않는다. 가격 변경이 드물고 마이그레이션 리뷰가 본다.
CREATE INDEX idx_model_price_books_lookup ON model_price_books (provider, model, effective_from);
