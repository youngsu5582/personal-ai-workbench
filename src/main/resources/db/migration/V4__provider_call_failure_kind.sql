-- 실패가 **어떻게** 났는지를 사유 문자열과 따로 적는다.
--
-- 나중에 "이 호출이 과금됐나" 를 판정하려면 이 구분이 필요하다. 지금은 그 정보가
-- failure_reason 안에만 있어서(`[openai 500 ...]`·`[openai 응답 없음] ...`),
-- 자동으로 가리려면 우리가 만든 메시지 포맷을 우리가 파싱해야 한다 — 메시지를 다듬는 순간 깨진다.
--
-- ExternalApiException.retryable 로는 못 가린다. 과금 관점에서 셋을 뭉치기 때문이다.
--   4xx        retryable=false   과금 안 됨
--   429 · 5xx  retryable=true    과금 안 됨
--   타임아웃    retryable=true    **됐을 수 있음** — 저쪽은 이미 만들었다
--
-- 값에 "과금됐다/안 됐다" 를 넣지 않는다. 그건 판정이고 단가표를 아는 쪽이 할 일이다.
-- 여기는 관측한 사실만 적는다.

-- CHECK 제약을 걸지 않는다.
--
-- 이 표는 **실패할 수 있는 제약을 두지 않는다**. 지출을 적는 INSERT 는 이미 돈을 쓴 뒤에
-- 일어나고, 실패하면 부르는 쪽이 삼킨다 — 제약에 걸리면 돈 기록이 조용히 사라진다.
-- FK 를 두지 않고 긴 문자열을 잘라 넣는 것과 같은 이유다.
--
-- 값 목록이 늘었는데 제약을 못 고치면 그 일이 실제로 일어난다. ddl-auto 도
-- SchemaMigrationTest 도 CHECK 는 보지 않아서 아무도 미리 못 잡는다.
--
-- 상태 컬럼(users.status 등)에 CHECK 를 거는 것과 성격이 다르다. 저기는 틀리면 상태 기계가
-- 깨지는 불변식이고 쓰기 실패가 요청으로 드러나지만, 여기는 관측이고 쓰기 실패가 삼켜진다.
-- 값은 애플리케이션의 enum 이 지킨다.
ALTER TABLE provider_calls
    ADD COLUMN failure_kind varchar(32);

-- 기존 행은 채우지 않는다. 사유 문자열을 파싱해 넣을 수도 있지만, 그건 이 컬럼을 만든 이유
-- 자체를 거스른다 — 파싱이 미덥지 않아서 컬럼을 두는 것이다.
-- 안 채워진 행은 "그때는 안 적었다" 로 남고, 비용도 null 로 남는다. 지어내는 것보다 낫다.
