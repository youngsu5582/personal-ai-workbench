-- 사용자가 보관소에 직접 올리기로 한 파일. 행은 **주소를 발급할 때** 생긴다.
--
-- 바이트는 클라이언트에서 보관소로 바로 가서 앱은 그 전송을 보지 못한다. 그래서 발급 시점에는
-- "이 자리에 이 형식·크기를 올려도 된다" 만 알고, 올라왔는지와 정말 그 형식인지는 처음 쓰일 때 확인해
-- status 로 남긴다. 확인 전(PENDING)과 불합격(REJECTED)은 입력으로 쓸 수 없다.
--
-- 한 행에 상태를 두고 두 테이블로 나누지 않는다. 불합격도 기록으로 남기는 편이
-- provider_calls 가 실패한 호출까지 적는 것과 같은 결이다.
--
-- 소유자를 users 의 대리키가 아니라 uuid 로 가리키고 FK 도 두지 않는다 — 근거는 V2.
CREATE TABLE uploaded_files (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid            uuid                        NOT NULL,
    owner_user_uuid uuid                        NOT NULL,
    storage_key     varchar(255)                NOT NULL,
    -- 형식과 크기. PENDING 이면 발급 때 선언한 값이고, READY 면 확인된 사실이다.
    --
    -- 컬럼으로 쪼개지 않는 이유는 generated_files.metadata 와 같다. 이 값으로 검색하거나 집계할 요구가 없고,
    -- 가로·세로처럼 바이트에서 읽을 사실이 더 붙을 자리다. 두 파일이 같은 모양으로 사실을 둔다.
    metadata        jsonb                       NOT NULL,
    status          varchar(255)                NOT NULL,
    created_at      timestamp(6) with time zone NOT NULL,
    updated_at      timestamp(6) with time zone NOT NULL,

    CONSTRAINT uk_uploaded_files_uuid UNIQUE (uuid),
    -- 행 하나가 객체 하나를 가리킨다. 불합격한 객체를 지워도 다른 행이 다치지 않는 근거다.
    -- generated_files 는 내용 주소라 객체를 공유하므로 이 제약이 없다.
    CONSTRAINT uk_uploaded_files_storage_key UNIQUE (storage_key),
    -- 값이 늘면 이 제약도 같이 고쳐야 한다. ddl-auto 는 이것을 갱신하지 못한다.
    CONSTRAINT ck_uploaded_files_status CHECK (status IN ('PENDING', 'READY', 'REJECTED'))
);
