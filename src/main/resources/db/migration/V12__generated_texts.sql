-- 만들어진 글. generated_files 의 짝이다 — Task 는 호출이고 결과물은 종류마다 자기 표에 둔다.
--
-- generation_job_tasks 에 칸을 두지 않는다. 이미지 Task 에서는 그 칸이 늘 비는데,
-- 그 NULL 은 "아직 안 끝났다" 와 모양이 같으면서 뜻은 "해당 없음" 이다.
CREATE TABLE generated_texts (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id       bigint                      NOT NULL,
    -- 모델이 낸 글 원문. 구조화된 답도 jsonb 가 아니라 text 다 — jsonb 는 키를 다시 늘어놓아
    -- 모델이 요청한 스키마 순서대로 낸 것을 잃는다.
    content       text                        NOT NULL,
    -- 저쪽이 이 결과물에 대해 알려준 것(응답 식별자 등). 아무것도 안 알려주면 NULL 이다.
    provider_info jsonb,
    created_at    timestamp(6) with time zone NOT NULL
);

-- 유니크 제약을 걸지 않는다. generated_files 와 같다 — "같은 Task 가 두 번 성공 처리되지 않는다" 는
-- Task 의 상태 전이가 지킨다. 인덱스는 Job 조회가 Task 별로 글을 모을 때 쓴다.
CREATE INDEX idx_generated_texts_task ON generated_texts (task_id);
