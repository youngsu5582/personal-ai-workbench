-- 판정 한 번의 답들. generated_texts 의 짝이다 — Task 는 호출이고 결과물은 종류마다 자기 표에 둔다.
CREATE TABLE generated_decisions (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id       bigint                      NOT NULL,
    -- 질문마다 하나인 답의 목록. 판별자는 원소 안의 type 이고 그 값이 행에 그대로 박힌다.
    -- 글과 달리 jsonb 다 — 키 순서가 아니라 목록 순서가 질문의 순서이고, 목록은 jsonb 가 지킨다.
    answers       jsonb                       NOT NULL,
    -- 저쪽이 이 결과물에 대해 알려준 것(응답 식별자 등). 아무것도 안 알려주면 NULL 이다.
    provider_info jsonb,
    created_at    timestamp(6) with time zone NOT NULL
);

-- 유니크 제약을 걸지 않는다. generated_texts 와 같다 — "같은 Task 가 두 번 성공 처리되지 않는다" 는
-- Task 의 상태 전이가 지킨다. 인덱스는 Job 조회가 Task 별로 답을 모을 때 쓴다.
CREATE INDEX idx_generated_decisions_task ON generated_decisions (task_id);
