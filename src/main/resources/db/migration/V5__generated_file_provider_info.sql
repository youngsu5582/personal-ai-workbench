-- 결과물에 대해 **Provider 가 추가로 알려준 것**을 파일의 속성과 따로 적는다.
--
-- metadata 는 바이트를 보면 알 수 있는 것만 담는다 — 크기·형식·용량. 파일을 다른 곳으로
-- 옮겨도 따라가는 값들이다. 반면 "모델이 실제로 쓴 문장" 이나 "저쪽이 붙인 번호" 는
-- 바이트에서 나오지 않고, 우리가 계산할 수도 없다. 저쪽이 말해줘야만 아는 것이다.
--
-- 한 칸에 섞으면 나중에 영상이 들어올 때 드러난다. 그때 metadata 는 duration·fps 로 바뀌지만
-- 이쪽은 그대로다 — 같이 변하지 않는 것이 한 칸에 있으면 안 된다.
--
-- 컬럼으로 쪼개지 않는 이유는 metadata 와 같다. 이 값으로 검색하거나 집계할 요구가 없다.
-- 요구가 생기면 그때 승격한다 — 승격은 되돌릴 수 있고, 버린 것은 되돌릴 수 없다.
--
-- nullable 이다. 아무것도 답해주지 않는 Provider 가 정상이고, 그때는 빈 객체가 아니라
-- 없는 것이 맞다. 기존 행도 채우지 않는다 — 그때는 받아놓고 버렸으므로 지어낼 것이 없다.
ALTER TABLE generated_files
    ADD COLUMN provider_info jsonb;
