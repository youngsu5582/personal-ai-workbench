CREATE TABLE generation_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    owner_user_uuid UUID NOT NULL,
    workspace_uuid UUID NOT NULL,
    name VARCHAR(255) NOT NULL,
    -- 실행 명세: 변수 자리를 둔 생성 옵션 · 실행 때 받을 이미지 수 · 기본 모델. 조회에 쓰지 않아 한 칸에 담는다.
    spec JSONB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_generation_templates_workspace ON generation_templates (owner_user_uuid, workspace_uuid, created_at DESC);
