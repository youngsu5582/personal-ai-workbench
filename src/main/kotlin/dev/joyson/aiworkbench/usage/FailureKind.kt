package dev.joyson.aiworkbench.usage

/**
 * 기록된 호출이 **어떻게** 실패했는가.
 *
 * 이 값이 있어야 나중에 **과금 여부를 판정**할 수 있다. 사유 문자열만 있으면
 * 우리가 만든 메시지 포맷을 우리가 파싱해야 하고, 그건 메시지를 다듬는 순간 깨진다.
 *
 * `provider` 모듈에도 같은 모양의 enum 이 있지만 그것을 쓰지 않는다 —
 * 저장되는 모양은 저장하는 모듈이 소유한다. 그쪽 이름을 박으면 Provider 쪽을 조정할 때
 * 기존 행을 못 읽는다. (`ImageMetadata` 와 `FileMetadata` 를 갈라 둔 것과 같은 판단이다.)
 *
 * 값에 "과금됐다/안 됐다" 를 넣지 않는다. 그건 **판정**이고 단가표를 아는 쪽이 할 일이다.
 * 여기는 관측한 사실만 적는다.
 */
enum class FailureKind {
    /** 요청이 틀렸다. 저쪽은 만들지 않았다. */
    REJECTED,

    /** 한도에 걸렸다. 아무것도 만들지 않았다. */
    THROTTLED,

    /** 저쪽의 오류다. 200 인데 결과물이 없는 응답도 여기 들어오며, 그쪽은 과금됐을 수 있다. */
    PROVIDER_ERROR,

    /**
     * 응답을 받지 못했다.
     *
     * **과금을 가장 의심해야 하는 종류다** — 타임아웃이면 저쪽은 이미 만들어 돈을 받았는데
     * 우리만 못 받았을 수 있다. 비용을 0 으로도 모름으로도 단정하면 안 된다.
     */
    NO_RESPONSE,

    /** 설명되지 않는 실패. */
    UNKNOWN,
}
